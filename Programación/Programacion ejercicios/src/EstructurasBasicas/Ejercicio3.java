package EstructurasBasicas;

public class Ejercicio3 {
    public static void main(String[] args) {
        //Tipo de variables
        String nombre = "Yair";
        //Recordar para dar valor a la variable String SIEMPRE entre comillas dobles
        int edad = 24;
        boolean estudiasEnPrometeo = true;
        double altura = 1.79;
        char inicial = 'Y';
        //Para dar valor a char entre comillas simples siempre
        System.out.println("Nombre: "+nombre+" | Tipo: String");
        System.out.println("Edad: "+edad+" | Tipo: Int");
        System.out.println("¿Estudia en prometeo? "+estudiasEnPrometeo+" | Tipo: boolean");
        System.out.println("Altura: "+altura+" | Tipo: double");
        System.out.println("Inicial: "+inicial+" | Tipo: char");

    }
}
